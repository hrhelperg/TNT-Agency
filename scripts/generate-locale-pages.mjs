/**
 * Writes an explicit static route file for every PUBLISHED localized concept.
 *
 * Explicit files, not a [slug] catch-all: a dynamic route would make Next
 * classify these as dynamic, and the architecture is asserted at 0 dynamic,
 * 0 SSG, 0 ISR. Each file is a thin wrapper — identity, canonical, hreflang and
 * content all resolve through the registry and the corpus — so the generated
 * code carries no decisions of its own.
 *
 * Idempotent: writes only when the content differs, so re-running produces no
 * churn. It never deletes, because deciding a page is obsolete is not a thing a
 * generator should do silently.
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath, pathToFileURL } from 'url'

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const reg = await import('../lib/locale/registry.ts')

const componentName = (id, locale) =>
  id.split(/[^a-zA-Z0-9]/).filter(Boolean).map((s) => s[0].toUpperCase() + s.slice(1)).join('') +
  locale[0].toUpperCase() + locale.slice(1) + 'Page'

export function generate({ write = true } = {}) {
  const written = []
  const unchanged = []
  for (const concept of reg.LOCALE_CONCEPTS) {
    for (const locale of concept.published) {
      if (locale === 'cs') continue
      const url = reg.urlFor(concept, locale)
      if (!url) continue
      // The locale root is pages/<locale>/index.tsx. Writing pages/<locale>.tsx
      // instead would create a SECOND file resolving to the same route, which
      // Next resolves silently and arbitrarily.
      const rel = url.replace(/^\//, '')
      const file = path.join(ROOT, 'pages', rel.includes('/') ? rel + '.tsx' : path.join(rel, 'index.tsx'))
      const corpus = locale === 'en' ? 'EN_CONTENT' : 'DE_CONTENT'
      const depth = path.relative(path.dirname(file), path.join(ROOT)).split(path.sep).length
      const up = '../'.repeat(depth)
      const body = `import LocalePage from '${up}components/locale/LocalePage'
import { ${corpus} } from '${up}lib/locale/content/${locale}'

// Generated by scripts/generate-locale-pages.mjs — do not edit by hand.
// Route identity, canonical, hreflang and content all resolve through the
// locale registry; this wrapper exists so the route is statically enumerable.
export default function ${componentName(concept.id, locale)}() {
  return <LocalePage conceptId="${concept.id}" locale="${locale}" content={${corpus}['${concept.id}'].${locale}!} />
}
`
      const existing = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null
      if (existing === body) { unchanged.push(url); continue }
      if (existing && !existing.includes('Generated by scripts/generate-locale-pages.mjs')) {
        // A hand-written page (the L0 routes, and request-staff which mounts a
        // form). Never overwrite one.
        unchanged.push(url + ' (hand-written, left alone)')
        continue
      }
      if (write) {
        fs.mkdirSync(path.dirname(file), { recursive: true })
        fs.writeFileSync(file, body)
      }
      written.push(url)
    }
  }
  return { written, unchanged }
}

const invokedDirectly = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href
if (invokedDirectly) {
  const { written, unchanged } = generate()
  console.log(`generated ${written.length} route file(s); ${unchanged.length} already correct`)
  written.forEach((u) => console.log('  + ' + u))
}
